function dateInMonth(monthsAgo: number, day: number): string {
  const now = new Date();
  const date = new Date(now.getFullYear(), now.getMonth() - monthsAgo, day);
  if (monthsAgo === 0 && date > now) {
    return toDateString(now);
  }
  return toDateString(date);
}

